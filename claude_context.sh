#!/bin/bash
# claude_context.sh - Drop-in replacement for 'cat /home/lumen/claude_memory.md' in Claude sessions.
#
# wq#4790: canonical tracked copy. Was /home/lumen/minerva/context/claude_context.sh,
# which minerva/.gitignore:18 ignores (context/ is "generated / prose stores"), so the
# real boot script had no history, no review and no rollback beyond ad-hoc .bak files
# (wq#4787 edit left claude_context.sh.bak.20261031_204528.wq4787 behind it). This copy
# is deployed by install.sh over /home/lumen/bin/claude_context.sh, which used to be
# only an `exec` shim into the untracked minerva copy. context/ keeps holding the files
# this script reads/writes at runtime (SESSION-BRIEFING.md, FLEET_TOOLS_BOOT.md,
# sections.json, LIVE_FLEET_STATE.md, context_selector.py) — those stay generated/
# runtime, not source, which is what context/ should have held all along.
#
# Usage:
#   /home/lumen/bin/claude_context.sh "your query here"        # full context for query
#   /home/lumen/bin/claude_context.sh --stats "your query"     # just the stats
#   /home/lumen/bin/claude_context.sh --core                    # core sections only (~2K tok)
#
# This is what Claude should use at session start INSTEAD of reading the full memory file.
# Saves ~90% tokens per session.
cd /home/lumen/minerva/context
if [ "$1" = "--core" ]; then
    # wq#1127: wq#1116 fixed collisions between two REGISTERED orchestrators but left the
    # anonymous-boot hole open — nothing at the wq chokepoint can tell two unregistered
    # same-host drivers apart (wq#594's docstring), so refuse to hand back a --core context
    # to a caller wq cannot vouch for. `wq whoami` always exits 0 regardless of registration
    # (it is a query, not a gate), so the status line has to be parsed.
    whoami_out=$(/home/lumen/bin/wq whoami 2>/dev/null)
    if grep -q '^status   : REGISTERED' <<<"$whoami_out"; then
        session_id=$(sed -n 's/^identity : \([^ ]*\).*/\1/p' <<<"$whoami_out")
        echo "===== REGISTERED SESSION: $session_id ====="
    else
        echo "REFUSED: --core requires a registered wq identity (wq#1127)."
        echo "Two unregistered same-host sessions are indistinguishable to wq and can step on"
        echo "each other's in-flight claims (wq#1116)."
        echo "Register first:  wq whoami --register orch-<slug>"
        echo "Then re-run:     bash $0 --core"
        exit 1
    fi
    /home/lumen/bin/handoff verify 2>/dev/null; echo
    # wq#4787: SESSION-BRIEFING.md is the generated situational briefing for the incoming agent,
    # read FIRST (before HANDOFF.md and the claude_memory.md selector below). Re-rendered here so
    # it is seconds old. Fail-open: a failed render keeps the previous file; no file prints nothing.
    timeout 20 /home/lumen/bin/session-briefing >/dev/null 2>&1
    if [ -f /home/lumen/minerva/context/SESSION-BRIEFING.md ]; then
        echo "===== SESSION-BRIEFING.md (read first — generated by bin/session-briefing, wq#4787) ====="
        cat /home/lumen/minerva/context/SESSION-BRIEFING.md
        echo "===== END SESSION-BRIEFING.md ====="
        echo
    fi
    # wq#1630: re-render the generated region at the top of HANDOFF.md (in-flight claims, last
    # landed PRs, detector stamps) so it is seconds old here, not up to 30 min — same pattern as
    # fleet-tools-render below. Fail-open: a failed render keeps the previous (timestamped) region.
    timeout 15 /home/lumen/bin/session-handoff --render >/dev/null 2>&1
    if [ -f /home/lumen/HANDOFF.md ]; then
        echo "===== HANDOFF.md (index — read after VERIFY above) ====="
        cat /home/lumen/HANDOFF.md
        echo "===== END HANDOFF.md ====="
        echo
    fi

    # FLEET_TOOLS — the system/fleet-wide capability registry (wq: injected 2026-09-09).
    # Re-render from fleet_tools.yaml so a drifted path is flagged at boot, never silently stale.
    # wq#4787: the block below cats FLEET_TOOLS_BOOT.md, which only `--boot` writes; a plain render
    # refreshed FLEET_TOOLS.md alone, so the injected boot copy sat stale (last 2026-10-27).
    /home/lumen/bin/fleet-tools-render >/dev/null 2>&1
    /home/lumen/bin/fleet-tools-render --boot >/dev/null 2>&1
    if [ -f /home/lumen/minerva/context/FLEET_TOOLS_BOOT.md ]; then
        echo "===== FLEET_TOOLS_BOOT.md (what tools exist + how to invoke — reach for these before hand-running) ====="
        cat /home/lumen/minerva/context/FLEET_TOOLS_BOOT.md
        echo "===== END FLEET_TOOLS_BOOT.md ====="
        echo
    fi
    # Memory V3 P3: accepted procedural instincts (review-gated file).
    # wq#958: this was `head -c 4096`, which delivered 22 of 57 rules — not the FULL AUTONOMY
    # grant, not the Thor hard rule — and cut mid-rule, so the block was corrupt YAML. The
    # renderer emits whole rules, tier-ordered, and names anything it leaves out. It prints
    # nothing when there is nothing to inject or the file is unusable.
    instincts=$(python3 /home/lumen/foreman/harness/instincts_render.py --audience boot 2>/dev/null)
    case $? in
        0)  echo "===== INSTINCTS (accepted procedural memory) ====="
            printf '%s\n' "$instincts"
            echo "===== END INSTINCTS ====="
            echo ;;
        3)  ;;  # empty or absent file — nothing to inject, and that is not a failure
        *)  echo "===== INSTINCTS UNAVAILABLE — instincts-render failed on /home/lumen/instincts.yaml;"
            echo "      read the file directly before acting on procedural memory ====="
            echo ;;
    esac
    # wq#1633: regen the state projections first if state_facts changed since the
    # last regen (MINERVA_PIPELINE_MAP.md §4.4/§5#5) — "forgot to run state-regen"
    # stops being a class of bug; the human step becomes a fast path, not the only one.
    /home/lumen/bin/state-regen --if-dirty
    python3 /home/lumen/minerva/projection_state.py check-warn live_fleet_state \
        --file /home/lumen/minerva/context/LIVE_FLEET_STATE.md
    if [ -f /home/lumen/minerva/context/sections.json ] \
        && [ /home/lumen/minerva/context/sections.json -ot /home/lumen/claude_memory.md ]; then
        echo "WARN: sections.json is older than claude_memory.md (wq#1633) — tag_sections may not have run"
    fi
    # wq#3647: regenerate claude_memory.md from the canonical fleet_memory DB
    # before the selector reads it. Fail-open: a builder error keeps the prior file.
    python3 /home/lumen/minerva/memory/context_builder.py --out /home/lumen/claude_memory.md 2>/dev/null \
        || echo "WARN: context_builder failed; using existing claude_memory.md (wq#3647)"
    python3 context_selector.py 'session start core context'
elif [ "$1" = "--stats" ]; then
    shift
    python3 context_selector.py "$@" --stats
else
    python3 context_selector.py "$@"
fi
